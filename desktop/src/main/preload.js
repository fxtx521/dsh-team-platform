'use strict';
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('wb', {
  snapshot: () => ipcRenderer.invoke('app:snapshot'),
  saveConfig: (patch) => ipcRenderer.invoke('app:saveConfig', patch),
  pickFolder: () => ipcRenderer.invoke('project:pickFolder'),
  addProject: (p) => ipcRenderer.invoke('project:add', p),
  removeProject: (id) => ipcRenderer.invoke('project:remove', id),
  listFiles: (p) => ipcRenderer.invoke('project:listFiles', p),
  readFile: (p) => ipcRenderer.invoke('project:readFile', p),
  writeFile: (p) => ipcRenderer.invoke('project:writeFile', p),
  openInFinder: (d) => ipcRenderer.invoke('project:openInFinder', d),
  reveal: (f) => ipcRenderer.invoke('project:reveal', f),
  runCmd: (p) => ipcRenderer.invoke('cmd:run', p),
  heartbeat: () => ipcRenderer.invoke('cloud:heartbeat'),
  chat: (m, sessionId, files, projectId, expertId) => ipcRenderer.invoke('cloud:chat', { message: m, sessionId, files, projectId, expertId }),
  experts: () => ipcRenderer.invoke('cloud:experts'),
  octopLogin: (u, p) => ipcRenderer.invoke('octop:login', { username: u, password: p }),
  octopExperts: () => ipcRenderer.invoke('octop:experts'),
  octopChat: (p) => ipcRenderer.invoke('octop:chat', p),
  mcpToggle: (on) => ipcRenderer.invoke('mcp:toggle', on),
  runTask: (p) => ipcRenderer.invoke('cloud:runTask', p),
  uploadArtifact: (p) => ipcRenderer.invoke('cloud:uploadArtifact', p),
  readBrief: (p) => ipcRenderer.invoke('project:readBrief', p),
  saveBrief: (p) => ipcRenderer.invoke('project:saveBrief', p),
  onTool: (cb) => ipcRenderer.on('app:tool', (_e, d) => cb(d)),
  mySummary: () => ipcRenderer.invoke('cloud:mySummary'),
  me: () => ipcRenderer.invoke('cloud:me'),
  login: (u, p) => ipcRenderer.invoke('auth:login', { username: u, password: p }),
  logout: () => ipcRenderer.invoke('auth:logout'),
  expAction: (p) => ipcRenderer.invoke('cloud:expAction', p),
  saveOutput: (p) => ipcRenderer.invoke('project:saveOutput', p),
  listTextFiles: (p) => ipcRenderer.invoke('project:listTextFiles', p),
  tasks: () => ipcRenderer.invoke('cloud:tasks'),
  skills: () => ipcRenderer.invoke('cloud:skills'),
  skillStats: () => ipcRenderer.invoke('cloud:skillStats'),
  minimize: () => ipcRenderer.invoke('window:minimize'),
  close: () => ipcRenderer.invoke('window:close'),
  onState: (cb) => ipcRenderer.on('app:state', (_e, d) => cb(d)),
  onLog: (cb) => ipcRenderer.on('app:log', (_e, d) => cb(d)),
  onGoto: (cb) => ipcRenderer.on('app:goto', (_e, d) => cb(d)),
});
